export function completionRequest(model, messages) {
  return {
    model,
    models: [...new Set([model, FALLBACK_MODEL])],
    provider: { max_price: { prompt: 0, completion: 0 } },
    stream: true,
    messages: [{ role: 'system', content: SYSTEM_PROMPT }, ...messages],
    temperature: 0.3,
    reasoning: { enabled: false },
    max_tokens: 2200,
  };
}
